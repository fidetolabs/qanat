"""A metric is a transform definition writing the metrics table.

`the-metric-set-belongs-to-the-qanat-and-the-threshold-to-the-person` already
decided that metric values are materialised, keyed by definition version and
date. It named no mechanism, and the mechanism is a transform definition:

    raw.documents --> normalized.facts --+
                                         +--> metrics    PER is one definition
    raw.prices --------------------------+                PBR is another

**A real metric has a date of its own.** `PER on 2024-05-03` is
`price(2024-05-03) / EPS(latest filing as of 2024-05-03)`, so the metrics table
is a time series and `time_columns` filters it exactly as it filters facts and
spans. A formula that takes the date as a *parameter* is a fact rescaled, not a
series, and is not materialised: storing a value under a date it does not mean
would be worse than computing it on the call.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from conftest import write_project_text

from qanat import metrics
from qanat.project import load, validate
from qanat.runner import run_all
from qanat.store import Store

ARCHITECTURE = """\
project: per
store: {store}
stages:
  - {{id: raw, kind: raw}}
  - {{id: features, kind: features}}
time_columns:
  raw.facts: as_of
  raw.prices: as_of
  features.metrics: date
corpus:
  facts: raw.facts
  metrics: features.metrics
ingestion_job_definitions:
  - id: land_facts
    to: [raw.facts]
    connector: csv
    key: [subject, as_of]
    options: {{path: ./seed/facts.csv}}
  - id: land_prices
    to: [raw.prices]
    connector: csv
    key: [subject, as_of]
    options: {{path: ./seed/prices.csv}}
"""

#: `price / EPS`, carrying the price's own date. The shape of a real metric.
PER = """\
SELECT pr.subject AS subject, pr.as_of AS date, pr.close / f.eps AS value
FROM raw__prices pr
JOIN raw__facts f ON f.subject = pr.subject
"""

#: A fact rescaled: the date arrives as a parameter and it collapses to one row
#: per subject. Not a series.
RESCALED = ("SELECT subject, max(eps) AS value FROM raw__facts "
            "WHERE CAST(as_of AS DATE) <= :as_of GROUP BY 1")


@pytest.fixture
def ready(tmp_path: Path):
    from conftest import STORE_KIND

    store_line = "./data" if STORE_KIND == "parquet" else "./data/qanat.duckdb"
    (tmp_path / "seed").mkdir(parents=True)
    (tmp_path / "seed" / "facts.csv").write_text(
        "subject,eps,as_of\nAAPL,6.0,2024-01-01\nMSFT,10.0,2024-01-01\n")
    (tmp_path / "seed" / "prices.csv").write_text(
        "subject,close,as_of\n"
        "AAPL,180,2024-05-03\nAAPL,186,2024-05-06\nMSFT,400,2024-05-03\n")
    write_project_text(tmp_path, ARCHITECTURE.format(store=store_line))

    project, root = load(tmp_path)
    store = Store(project.store_url(root))
    assert all(r.ok for r in run_all(store, project, root))
    try:
        yield load(tmp_path) + (store,)
    finally:
        store.close()


# ---- A7: a metric is a transform definition ----------------------------------
def test_defining_a_series_writes_a_transform_and_a_script(ready):
    project, root, store = ready
    out = metrics.define(store, project, root, mid="per", unit="ratio", sql=PER)

    assert out["series"] is True
    assert out["transform"] == "metric_per_v1"
    assert out["table"] == "features.metrics"

    project, root = load(root)
    definition = project.definition("metric_per_v1")
    assert definition is not None
    assert definition.reads == ["raw.facts", "raw.prices"], "both inputs, from the formula"
    assert definition.writes == ["features.metrics"]
    assert definition.key == list(metrics.METRIC_KEY), "a metric value is never replaced"
    assert (root / definition.script).is_file()
    assert validate(project, root).ok


def test_the_generated_script_says_not_to_edit_it(ready):
    project, root, store = ready
    metrics.define(store, project, root, mid="per", sql=PER)
    body = (root / metrics.script_path("per", 1)).read_text()
    assert "Edit the definition" in body
    assert "generated by define_metric" in body


def test_running_it_lands_one_row_per_subject_per_date(ready):
    project, root, store = ready
    metrics.define(store, project, root, mid="per", sql=PER)
    project, root = load(root)
    assert all(r.ok for r in run_all(store, project, root))

    got = store.read("features.metrics")
    assert set(got.columns) == {"subject", "date", "metric", "version", "value"}
    assert len(got) == 3
    one = got[(got["subject"] == "AAPL") & (got["date"].astype(str) == "2024-05-03")]
    assert float(one["value"].iloc[0]) == 30.0, "180 / 6"


def test_a_metric_value_resolves_to_one_fact_row_and_one_price_row(ready):
    """**The acceptance test the task named.** Four hops from a number to a
    reason: the row names its execution, the execution its job, the job its
    definition, and the definition what it read."""
    project, root, store = ready
    metrics.define(store, project, root, mid="per", sql=PER)
    project, root = load(root)
    run_all(store, project, root)

    out = store.provenance("features.metrics",
                           where="subject = ? AND CAST(date AS DATE) = CAST(? AS DATE)",
                           params=["AAPL", "2024-05-03"])
    assert [e["rows"] for e in out["executions"]] == [1]
    one = out["executions"][0]
    assert one["definition"] == "metric_per_v1"
    assert one["definition_version"], "and which version of it was running"

    definition = project.definition(one["definition"])
    assert set(definition.reads) == {"raw.facts", "raw.prices"}

    # One row each on the other side of the join, which is what makes the value
    # a number somebody can check rather than an aggregate they have to trust.
    facts = store.rows("raw.facts", where="subject = ?", params=["AAPL"])
    prices = store.rows("raw.prices",
                        where="subject = ? AND CAST(as_of AS DATE) = CAST(? AS DATE)",
                        params=["AAPL", "2024-05-03"])
    assert len(facts) == 1 and len(prices) == 1


# ---- a corrected price -------------------------------------------------------
def test_a_corrected_price_leaves_the_old_metric_value_readable(ready):
    """**The question materialising forces**, answered here rather than left to
    whoever writes the job: the old value is what the user was shown, so it is
    the one that cannot be lost."""
    project, root, store = ready
    metrics.define(store, project, root, mid="per", sql=PER)
    project, root = load(root)
    run_all(store, project, root)

    (root / "seed" / "prices.csv").write_text(
        "subject,close,as_of\n"
        "AAPL,186,2024-05-03\nAAPL,186,2024-05-06\nMSFT,400,2024-05-03\n")
    assert all(r.ok for r in run_all(store, project, root))

    plain = store.read("features.metrics")
    one = plain[(plain["subject"] == "AAPL") & (plain["date"].astype(str) == "2024-05-03")]
    assert len(one) == 1, "a plain read returns one value for one day"
    assert float(one["value"].iloc[0]) == 31.0, "and it is the corrected one"

    held = store.con.execute(
        f'SELECT value FROM "{store.home}"."features__metrics" '
        f"WHERE subject = 'AAPL' AND CAST(date AS DATE) = DATE '2024-05-03' "
        f"ORDER BY value").df()
    assert [float(v) for v in held["value"]] == [30.0, 31.0], \
        "the value somebody was already shown is still there"


def test_recomputing_with_nothing_changed_writes_nothing(ready):
    project, root, store = ready
    metrics.define(store, project, root, mid="per", sql=PER)
    project, root = load(root)
    first = {r.definition_id: r for r in run_all(store, project, root)}
    assert first["metric_per_v1"].rows == 3

    again = {r.definition_id: r for r in run_all(store, project, root)}
    assert again["metric_per_v1"].rows == 0, "the same values are not stored twice"
    assert len(store.read("features.metrics")) == 3


# ---- versions ----------------------------------------------------------------
def test_a_bumped_version_gets_its_own_transform_and_both_resolve(ready):
    project, root, store = ready
    metrics.define(store, project, root, mid="per", sql=PER)
    project, root = load(root)
    run_all(store, project, root)

    # version 2: the same arithmetic on a different basis
    metrics.define(store, project, root, mid="per", version=2,
                   sql=PER.replace("pr.close / f.eps", "pr.close / (f.eps * 2)"))
    project, root = load(root)
    assert project.definition("metric_per_v1") is not None
    assert project.definition("metric_per_v2") is not None
    assert (root / metrics.script_path("per", 1)).is_file()
    assert (root / metrics.script_path("per", 2)).is_file()
    assert validate(project, root).ok

    run_all(store, project, root)
    got = store.read("features.metrics")
    both = got[(got["subject"] == "AAPL") & (got["date"].astype(str) == "2024-05-03")]
    assert sorted(int(v) for v in both["version"]) == [1, 2]
    assert sorted(float(v) for v in both["value"]) == [15.0, 30.0], \
        "an answer pointing at version 1 still returns"


def test_removing_a_version_takes_its_transform_with_it(ready):
    """A transform left behind would keep writing rows for a definition nothing
    can resolve, which is worse than keeping both or dropping both."""
    project, root, store = ready
    metrics.define(store, project, root, mid="per", sql=PER)
    project, root = load(root)
    metrics.define(store, project, root, mid="per", version=2, sql=PER)
    project, root = load(root)

    metrics.remove(project, root, mid="per", version=1)
    project, root = load(root)
    assert project.definition("metric_per_v1") is None
    assert project.definition("metric_per_v2") is not None
    assert not (root / metrics.script_path("per", 1)).exists()
    assert validate(project, root).ok


# ---- the other shape ---------------------------------------------------------
def test_a_formula_taking_the_date_as_a_parameter_is_not_materialised(ready):
    """It is a fact rescaled. Storing it under a date it does not mean would be
    worse than computing it on the call, so it is computed on the call -- and the
    answer says which kind it stored rather than leaving the caller to guess."""
    project, root, store = ready
    out = metrics.define(store, project, root, mid="eps_max", sql=RESCALED)

    assert out["series"] is False
    assert out["transform"] is None
    assert any("not a series" in w for w in out["warnings"]), out["warnings"]

    project, root = load(root)
    assert project.metric("eps_max") is not None, "stored, and still screenable"
    assert not [d for d in project.definitions if d.id.startswith("metric_")]


def test_a_series_is_refused_a_materialising_table_this_project_does_not_name(
        tmp_path: Path):
    from conftest import STORE_KIND

    store_line = "./data" if STORE_KIND == "parquet" else "./data/qanat.duckdb"
    (tmp_path / "seed").mkdir(parents=True)
    (tmp_path / "seed" / "facts.csv").write_text("subject,eps,as_of\nAAPL,6.0,2024-01-01\n")
    (tmp_path / "seed" / "prices.csv").write_text("subject,close,as_of\nAAPL,180,2024-05-03\n")
    write_project_text(tmp_path, ARCHITECTURE.format(store=store_line).replace(
        "  metrics: features.metrics\n", ""))
    project, root = load(tmp_path)
    store = Store(project.store_url(root))
    try:
        run_all(store, project, root)
        project, root = load(tmp_path)
        out = metrics.define(store, project, root, mid="per", sql=PER)
        assert out["transform"] is None
        assert any("corpus.metrics" in w for w in out["warnings"]), out["warnings"]
    finally:
        store.close()


# ---- a screen reads what was stored ------------------------------------------
def test_a_screen_resolves_a_clause_against_the_stored_value(ready):
    """A materialised value is what somebody was shown. Recomputing instead would
    answer the question a second time rather than answering what the first answer
    was."""
    from qanat.screen import stored_metric_values

    project, root, store = ready
    metrics.define(store, project, root, mid="per", sql=PER)
    project, root = load(root)
    run_all(store, project, root)

    got = stored_metric_values(store, project, project.metric("per"), "2024-05-04")
    assert got is not None
    assert dict(zip(got["subject"], got["value"], strict=True)) == {
        "AAPL": 30.0, "MSFT": 40.0}

    # The newest date at or before the one asked about, not an exact match: on a
    # day a subject had no new filing the series has not moved, and an exact
    # match would answer nothing.
    later = stored_metric_values(store, project, project.metric("per"), "2024-06-01")
    assert dict(zip(later["subject"], later["value"], strict=True))["AAPL"] == 31.0

    before = stored_metric_values(store, project, project.metric("per"), "2024-01-01")
    assert before is None, "nothing had been computed yet, so the formula runs instead"
