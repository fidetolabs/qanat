"""A metric is a transform definition writing its own table.

`the-metric-set-belongs-to-the-qanat-and-the-threshold-to-the-person` already
decided that metric values are materialised, keyed by definition version and
date. It named no mechanism, and the mechanism is a transform definition:

    raw.facts  --+
                 +--> per --> metrics.per --> per_rank --> metrics.per_rank
    raw.prices --+

**One table per metric, because metrics derive from each other.** A rank reads
the metric it ranks, and with one shared table that is a transform reading the
table it writes -- which `check` refuses, and which the run order cannot
sequence anyway, since it resolves a dependency per table.

**A metric has a date of its own.** `PER on 2024-05-03` is
`price(2024-05-03) / EPS(latest filing as of 2024-05-03)`, so a metric table is
a time series and `time_columns` filters it exactly as it filters facts and
spans. A formula taking the date as a *parameter* is refused: it stored nothing,
so it had no execution to name and no lineage -- and a screen had to run it,
which could read a figure from before it was public.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from conftest import write_project_text

from qanat import metrics
from qanat.project import load, validate
from qanat.runner import run_all
from qanat.store import Store

ARCHITECTURE = """\
project: per
store: {store}
stages:
  - {{id: raw, kind: raw}}
  - {{id: metrics, kind: metrics}}
time_columns:
  raw.facts: as_of
  raw.prices: as_of
  metrics.per: date
  metrics.per_rank: date
corpus:
  facts: raw.facts
ingestion_job_definitions:
  - id: land_facts
    to: [raw.facts]
    connector: csv
    key: [subject, as_of]
    options: {{path: ./seed/facts.csv}}
  - id: land_prices
    to: [raw.prices]
    connector: csv
    key: [subject, as_of]
    options: {{path: ./seed/prices.csv}}
"""

#: `price / EPS`, carrying the price's own date. The shape of a real metric.
PER = """\
SELECT pr.subject AS subject, pr.as_of AS date, pr.close / f.eps AS value
FROM raw__prices pr
JOIN raw__facts f ON f.subject = pr.subject
"""

#: A metric computed from another metric. The reason a metric is a table.
PER_RANK = """\
SELECT subject, date,
       CAST(rank() OVER (PARTITION BY date ORDER BY value) AS DOUBLE) AS value
FROM metrics__per
"""

#: The date arrives as a parameter and it collapses to one row per subject.
#: Refused: it would store nothing, so there would be nothing to trace.
RESCALED = ("SELECT subject, max(eps) AS value FROM raw__facts "
            "WHERE CAST(as_of AS DATE) <= :as_of GROUP BY 1")


@pytest.fixture
def ready(tmp_path: Path):
    from conftest import STORE_KIND

    store_line = "./data" if STORE_KIND == "parquet" else "./data/qanat.duckdb"
    (tmp_path / "seed").mkdir(parents=True)
    (tmp_path / "seed" / "facts.csv").write_text(
        "subject,eps,as_of\nAAPL,6.0,2024-01-01\nMSFT,10.0,2024-01-01\n")
    (tmp_path / "seed" / "prices.csv").write_text(
        "subject,close,as_of\n"
        "AAPL,180,2024-05-03\nAAPL,186,2024-05-06\nMSFT,400,2024-05-03\n")
    write_project_text(tmp_path, ARCHITECTURE.format(store=store_line))

    project, root = load(tmp_path)
    store = Store(project.store_url(root))
    assert all(r.ok for r in run_all(store, project, root))
    try:
        yield load(tmp_path) + (store,)
    finally:
        store.close()


# ---- A7: a metric is a transform definition ----------------------------------
def test_defining_a_metric_writes_a_transform_and_a_script(ready):
    project, root, store = ready
    out = metrics.define(store, project, root, mid="per", unit="ratio", sql=PER)

    assert out["transform"] == "per", "the definition is the metric's own name"
    assert out["table"] == "metrics.per"

    project, root = load(root)
    definition = project.definition("per")
    assert definition is not None
    assert definition.reads == ["raw.facts", "raw.prices"], "both inputs, from the formula"
    assert definition.writes == ["metrics.per"]
    assert definition.key == list(metrics.METRIC_KEY), "a metric value is never replaced"
    assert definition.options.get("unit") == "ratio", "unit rides on the definition"
    assert (root / definition.script).is_file()
    assert validate(project, root).ok


def test_the_generated_script_says_not_to_edit_it(ready):
    project, root, store = ready
    metrics.define(store, project, root, mid="per", sql=PER)
    body = (root / metrics.script_path("per")).read_text()
    assert "Edit the definition" in body
    assert "generated by define_metric" in body


def test_it_lands_one_row_per_subject_per_date_with_no_name_or_version_column(ready):
    """**The table's name is the metric's name**, so there is no `metric` column;
    and the version is the digest the execution recorded, so there is no
    `version` column either. A literal there could not move when the formula
    did -- measured, halving a formula appended values all still labelled 1."""
    project, root, store = ready
    metrics.define(store, project, root, mid="per", sql=PER)

    got = store.read("metrics.per")
    assert set(got.columns) == {"subject", "date", "value"}
    assert len(got) == 3
    one = got[(got["subject"] == "AAPL") & (got["date"].astype(str) == "2024-05-03")]
    assert float(one["value"].iloc[0]) == 30.0, "180 / 6"


def test_a_metric_value_resolves_to_one_fact_row_and_one_price_row(ready):
    """**The acceptance test the task named.** Four hops from a number to a
    reason: the row names its execution, the execution its job and the digest it
    ran, the job its definition, and the definition what it read."""
    project, root, store = ready
    metrics.define(store, project, root, mid="per", sql=PER)
    project, root = load(root)

    out = store.provenance("metrics.per",
                           where="subject = ? AND CAST(date AS DATE) = CAST(? AS DATE)",
                           params=["AAPL", "2024-05-03"])
    assert [e["rows"] for e in out["executions"]] == [1]
    one = out["executions"][0]
    assert one["definition"] == "per"
    assert one["definition_version"], "and which version of it was running"
    assert "not recorded" not in one["definition_version"], \
        "the digest was recorded on the attempt, not looked up afterwards"

    definition = project.definition(one["definition"])
    assert set(definition.reads) == {"raw.facts", "raw.prices"}

    # One row each on the other side of the join, which is what makes the value
    # a number somebody can check rather than an aggregate they have to trust.
    facts = store.rows("raw.facts", where="subject = ?", params=["AAPL"])
    prices = store.rows("raw.prices",
                        where="subject = ? AND CAST(as_of AS DATE) = CAST(? AS DATE)",
                        params=["AAPL", "2024-05-03"])
    assert len(facts) == 1 and len(prices) == 1


# ---- a metric from a metric ---------------------------------------------------
def test_a_metric_can_read_another_metric(ready):
    """**The reason a metric is a table.** With one shared metrics table this is
    a transform reading the table it writes: `check` refuses it, and the run
    order resolves a dependency per table -- so a shared table counts as
    produced the moment any metric writes it, and a chain cannot be sequenced.
    """
    project, root, store = ready
    metrics.define(store, project, root, mid="per", sql=PER)
    project, root = load(root)
    out = metrics.define(store, project, root, mid="per_rank", sql=PER_RANK)

    assert out["reads"] == ["metrics.per"]
    project, root = load(root)
    assert validate(project, root).ok, validate(project, root).errors

    from qanat.runner import order

    sequence = [d.id for d in order(project)]
    assert sequence.index("per") < sequence.index("per_rank"), \
        "the dependency is real, so the order is computable"

    got = store.read("metrics.per_rank")
    on_the_third = got[got["date"].astype(str) == "2024-05-03"]
    assert sorted(float(v) for v in on_the_third["value"]) == [1.0, 2.0]


def test_a_chain_orders_itself_however_it_is_declared(ready):
    """Declared deepest-first, a shared table scheduled the dependent before its
    input. The edge is what orders it, not the file."""
    from qanat.runner import order

    project, root, store = ready
    metrics.define(store, project, root, mid="per", sql=PER)
    project, root = load(root)
    metrics.define(store, project, root, mid="per_rank", sql=PER_RANK)
    project, root = load(root)

    # Put the deepest one first in the file.
    jobs = (root / "jobs.yaml").read_text()
    assert "per_rank" in jobs
    sequence = [d.id for d in order(project)]
    assert sequence.index("per") < sequence.index("per_rank")


# ---- a corrected price -------------------------------------------------------
def test_a_corrected_price_leaves_the_old_metric_value_readable(ready):
    """**The question materialising forces**, answered here rather than left to
    whoever writes the job: the old value is what the user was shown, so it is
    the one that cannot be lost."""
    project, root, store = ready
    metrics.define(store, project, root, mid="per", sql=PER)
    project, root = load(root)

    (root / "seed" / "prices.csv").write_text(
        "subject,close,as_of\n"
        "AAPL,186,2024-05-03\nAAPL,186,2024-05-06\nMSFT,400,2024-05-03\n")
    assert all(r.ok for r in run_all(store, project, root))

    plain = store.read("metrics.per")
    one = plain[(plain["subject"] == "AAPL") & (plain["date"].astype(str) == "2024-05-03")]
    assert len(one) == 1, "a plain read returns one value for one day"
    assert float(one["value"].iloc[0]) == 31.0, "and it is the corrected one"

    held = store.query(
        f'SELECT value FROM {store.raw_ref("metrics.per")} '
        f"WHERE subject = 'AAPL' AND CAST(date AS DATE) = DATE '2024-05-03' "
        f"ORDER BY value")
    assert [float(v) for v in held["value"]] == [30.0, 31.0], \
        "the value somebody was already shown is still there"


def test_recomputing_with_nothing_changed_writes_nothing(ready):
    project, root, store = ready
    metrics.define(store, project, root, mid="per", sql=PER)
    project, root = load(root)

    again = {r.definition_id: r for r in run_all(store, project, root)}
    assert again["per"].rows == 0, "the same values are not stored twice"
    assert len(store.read("metrics.per")) == 3


# ---- replacing a formula ------------------------------------------------------
def test_replacing_a_formula_keeps_both_answers_and_moves_the_digest(ready):
    """What replaced bumping a version. Both values are in the table, each
    naming the execution that wrote it, and the digest moved with the formula --
    which an integer alongside could not be relied on to do."""
    project, root, store = ready
    first = metrics.define(store, project, root, mid="per", sql=PER)
    project, root = load(root)
    second = metrics.define(store, project, root, mid="per",
                            sql=PER.replace("pr.close / f.eps", "pr.close / (f.eps * 2)"))
    assert second["version"] != first["version"]

    held = store.query(
        f'SELECT value FROM {store.raw_ref("metrics.per")} '
        f"WHERE subject = 'AAPL' AND CAST(date AS DATE) = DATE '2024-05-03' "
        f"ORDER BY value")
    assert [float(v) for v in held["value"]] == [15.0, 30.0], \
        "an answer pointing at the first formula still has its number"


def test_removing_a_metric_takes_its_transform_and_script(ready):
    """A transform left behind would keep writing rows for a definition nothing
    can resolve, which is worse than keeping both or dropping both."""
    project, root, store = ready
    metrics.define(store, project, root, mid="per", sql=PER)
    project, root = load(root)

    metrics.remove(project, root, mid="per", force=True)
    project, root = load(root)
    assert project.definition("per") is None
    assert not (root / metrics.script_path("per")).exists()
    assert validate(project, root).ok


# ---- the other shape, now refused --------------------------------------------
def test_a_formula_taking_the_date_as_a_parameter_is_refused(ready):
    """It stored nothing, so there was no row to name an execution and no
    lineage at all -- and a screen had to run the formula, which with no date to
    bind ran over every row."""
    project, root, store = ready
    with pytest.raises(metrics.MetricError, match=r":as_of"):
        metrics.define(store, project, root, mid="eps_max", sql=RESCALED)

    project, root = load(root)
    assert project.metric_ids() == [], "nothing was stored"


def test_a_project_with_no_metrics_stage_is_told_to_add_one(tmp_path: Path):
    from conftest import STORE_KIND

    store_line = "./data" if STORE_KIND == "parquet" else "./data/qanat.duckdb"
    (tmp_path / "seed").mkdir(parents=True)
    (tmp_path / "seed" / "facts.csv").write_text("subject,eps,as_of\nAAPL,6.0,2024-01-01\n")
    (tmp_path / "seed" / "prices.csv").write_text("subject,close,as_of\nAAPL,180,2024-05-03\n")
    write_project_text(tmp_path, ARCHITECTURE.format(store=store_line).replace(
        "  - {id: metrics, kind: metrics}\n", "").replace(
        "  metrics.per: date\n", "").replace("  metrics.per_rank: date\n", ""))
    project, root = load(tmp_path)
    store = Store(project.store_url(root))
    try:
        run_all(store, project, root)
        project, root = load(tmp_path)
        with pytest.raises(metrics.MetricError, match="kind: metrics"):
            metrics.define(store, project, root, mid="per", sql=PER)
    finally:
        store.close()


# ---- a screen reads what was stored ------------------------------------------
def test_a_screen_resolves_a_clause_against_the_stored_value(ready):
    """A materialised value is what somebody was shown. **There is no other
    path**: a value computed on the call leaves no row, so nothing could trace
    it."""
    from qanat.screen import metric_values

    project, root, store = ready
    metrics.define(store, project, root, mid="per", sql=PER)
    project, root = load(root)

    got = metric_values(store, project, "per", "2024-05-04")
    assert dict(zip(got["subject"], got["value"], strict=True)) == {
        "AAPL": 30.0, "MSFT": 40.0}

    # The newest date at or before the one asked about, not an exact match: on a
    # day a subject had no new value the series has not moved, and an exact
    # match would answer nothing.
    later = metric_values(store, project, "per", "2024-05-07")
    assert float(later[later.subject == "AAPL"].value.iloc[0]) == 31.0, "186 / 6"
    assert float(later[later.subject == "MSFT"].value.iloc[0]) == 40.0, "unchanged"


def test_a_date_before_every_row_evaluates_nothing_rather_than_guessing(ready):
    """**The look-ahead leak the fallback caused.** With nothing stored at or
    before the date, the old code ran the formula instead -- and a dated series
    has no `:as_of` to bind, so it ran over every row and the screen took
    whichever came first."""
    from qanat.screen import metric_values

    project, root, store = ready
    metrics.define(store, project, root, mid="per", sql=PER)
    project, root = load(root)

    got = metric_values(store, project, "per", "2024-01-15")
    assert got.empty, "nothing was public yet, so nothing is evaluated"
